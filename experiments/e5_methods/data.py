"""The three generated corpora of experiment E5, each with its ground truth.

Why: a method is chosen on one set of documents and judged on another. Choosing and judging
on the same text flatters the method (PREREGISTRATION.md, "The data").

Contract: `load(name)` gives the documents of one corpus, generated by E4's generator from a
fixed seed, so every run sees the same text. `e4` is E4's own corpus, unchanged. `select` and
`heldout` are E5's: other templates, other name banks.

Known limits: all three are written by the same author in the same hand, and no text is a real
document. What a method gains here is an upper bound on what it gains on a client's file.
"""

from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
E4 = HERE.parent / "e4_planted_names"
# `python -I` drops the script folder, and E4's generator is reused, not copied.
sys.path[:0] = [str(HERE), str(E4)]

import generate

# name -> (templates folder, name bank, seed). E4's seed is the one E4 was run with.
DATASETS = {
    "e4": (E4 / "templates", E4 / "names.tsv", generate.SEED),
    "select": (HERE / "templates_select", HERE / "names_select.tsv", "e5-select"),
    "heldout": (HERE / "templates_heldout", HERE / "names_heldout.tsv", "e5-heldout"),
}
# The forms in which a person is named by a name of their own, not as part of a group.
OWN_NAME_FORMS = frozenset(generate.FORM_BUCKETS) - frozenset(generate.GROUP_WORDS)


def load(name: str) -> list[generate.Document]:
    """Generate one corpus.

    Contract: `name` is a key of DATASETS; KeyError otherwise. The generator's seed is put
    back afterwards, so loading one corpus does not change the next.
    """
    templates, bank, seed = DATASETS[name]
    before = generate.SEED
    generate.SEED = seed
    try:
        return generate.corpus(templates, bank)
    finally:
        generate.SEED = before


def lonely(document: generate.Document) -> set[int]:
    """Return the positions, in `document.gold`, of mentions of a person named once only.

    Why: a method that carries a name from one place of a document to another cannot help
    such a mention. Its row in the report shows what is left when that method has done all
    it can.

    Contract: counted mentions only; a person is the template's key, so two people who
    share a surname are two people.
    """
    times = Counter(gold.person for gold in document.gold if gold.counted)
    return {
        index
        for index, gold in enumerate(document.gold)
        if gold.counted and gold.form in OWN_NAME_FORMS and times[gold.person] == 1
    }
